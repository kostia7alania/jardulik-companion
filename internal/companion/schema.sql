PRAGMA journal_mode=WAL;
PRAGMA foreign_keys=ON;
PRAGMA busy_timeout=5000;
CREATE TABLE IF NOT EXISTS meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS users (
 id INTEGER PRIMARY KEY, source TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
 feed_page INTEGER NOT NULL DEFAULT 1, paused INTEGER NOT NULL DEFAULT 0, first_card_at TEXT
);
CREATE TABLE IF NOT EXISTS sessions (
 owner_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 upstream_id INTEGER NOT NULL, encrypted BLOB NOT NULL, expires_at INTEGER NOT NULL DEFAULT 0,
 state TEXT NOT NULL DEFAULT 'connected', last_error TEXT NOT NULL DEFAULT '', account_json TEXT NOT NULL DEFAULT '{}', updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS versions (
 id INTEGER PRIMARY KEY AUTOINCREMENT, owner_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 profile_id INTEGER NOT NULL, fingerprint TEXT NOT NULL, text_fingerprint TEXT NOT NULL,
 raw_json TEXT NOT NULL, first_seen TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, last_seen TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(owner_id, profile_id, fingerprint)
);
CREATE INDEX IF NOT EXISTS versions_owner_profile ON versions(owner_id, profile_id, id DESC);
CREATE TABLE IF NOT EXISTS observations (
 id INTEGER PRIMARY KEY, owner_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 version_id INTEGER NOT NULL REFERENCES versions(id) ON DELETE CASCADE, source TEXT NOT NULL,
 observed_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS media (
 sha TEXT PRIMARY KEY, size INTEGER NOT NULL, mime TEXT NOT NULL, path TEXT NOT NULL, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS media_jobs (
 id INTEGER PRIMARY KEY, owner_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 version_id INTEGER NOT NULL REFERENCES versions(id) ON DELETE CASCADE, position INTEGER NOT NULL,
 role TEXT NOT NULL, url TEXT NOT NULL, sha TEXT REFERENCES media(sha), state TEXT NOT NULL DEFAULT 'pending', error TEXT NOT NULL DEFAULT '', attempts INTEGER NOT NULL DEFAULT 0, next_attempt INTEGER NOT NULL DEFAULT 0,
 UNIQUE(version_id, role, position)
);
CREATE INDEX IF NOT EXISTS media_pending ON media_jobs(state,id);
CREATE TABLE IF NOT EXISTS queue (
 owner_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, profile_id INTEGER NOT NULL,
 version_id INTEGER NOT NULL REFERENCES versions(id), delivered INTEGER NOT NULL DEFAULT 0, PRIMARY KEY(owner_id,profile_id)
);
CREATE TABLE IF NOT EXISTS favorites (
 owner_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, profile_id INTEGER NOT NULL,
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(owner_id,profile_id)
);
CREATE TABLE IF NOT EXISTS actions (
 id INTEGER PRIMARY KEY, owner_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, profile_id INTEGER NOT NULL,
 kind TEXT NOT NULL, state TEXT NOT NULL, response TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS actions_no_duplicate ON actions(owner_id,profile_id,kind) WHERE state IN ('pending','succeeded','unknown');
CREATE TABLE IF NOT EXISTS updates (id INTEGER PRIMARY KEY, state TEXT NOT NULL, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS deliveries (
 id INTEGER PRIMARY KEY, owner_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, version_id INTEGER NOT NULL REFERENCES versions(id) ON DELETE CASCADE,
 state TEXT NOT NULL, message_ids TEXT NOT NULL DEFAULT '[]', created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS events (
 id INTEGER PRIMARY KEY, owner_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 kind TEXT NOT NULL, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS mirror_topics (profile_id INTEGER PRIMARY KEY, thread_id INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS mirror_posts (fingerprint TEXT PRIMARY KEY, profile_id INTEGER NOT NULL, thread_id INTEGER NOT NULL, message_ids TEXT NOT NULL, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS backup_files (
 source_sha TEXT PRIMARY KEY, kind TEXT NOT NULL, filename TEXT NOT NULL, size INTEGER NOT NULL,
 chat_id INTEGER NOT NULL, thread_id INTEGER NOT NULL, message_id INTEGER NOT NULL, file_id TEXT NOT NULL, encrypted_sha TEXT NOT NULL DEFAULT '', sent_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS deletions (owner_id INTEGER PRIMARY KEY, deleted_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS gc_jobs (sha TEXT PRIMARY KEY, path TEXT NOT NULL);
